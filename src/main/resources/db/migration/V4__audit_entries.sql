-- The audit trail.
--
-- No foreign key to the printer table on purpose. A machine that is taken off the site must not
-- take the record of what was done to it with it, and a cascade would do exactly that.

CREATE TABLE audit_entries (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    actor VARCHAR(32) DEFAULT '' NOT NULL,
    action VARCHAR(32) NOT NULL,
    printer_id VARCHAR(32) DEFAULT '' NOT NULL,
    subject VARCHAR(64) DEFAULT '' NOT NULL,
    before VARCHAR(255) DEFAULT '' NOT NULL,
    after VARCHAR(255) DEFAULT '' NOT NULL,
    detail VARCHAR(255) DEFAULT '' NOT NULL,
    CONSTRAINT pk_audit_entries PRIMARY KEY (id)
);
CREATE INDEX ix_audit_entries_actor ON audit_entries (actor);
CREATE INDEX ix_audit_entries_action ON audit_entries (action);
CREATE INDEX ix_audit_entries_at ON audit_entries (at);
CREATE INDEX ix_audit_entries_at_printer ON audit_entries (at, printer_id);
