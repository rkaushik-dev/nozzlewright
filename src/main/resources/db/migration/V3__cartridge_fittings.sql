-- The fitting history: one row per cartridge per pen, from fitting to removal.

CREATE TABLE cartridge_fittings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    printer_pk INTEGER NOT NULL,
    pen INTEGER NOT NULL,
    serial VARCHAR(32) NOT NULL,
    part_number VARCHAR(32) DEFAULT '' NOT NULL,
    ink_family VARCHAR(16) DEFAULT '' NOT NULL,
    fitted_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    removed_at TIMESTAMP(6) WITH TIME ZONE,
    first_level INTEGER DEFAULT 100 NOT NULL,
    last_level INTEGER DEFAULT 100 NOT NULL,
    readings INTEGER DEFAULT 1 NOT NULL,
    CONSTRAINT pk_cartridge_fittings PRIMARY KEY (id),
    CONSTRAINT fk_cartridge_fittings_printer_pk_printers FOREIGN KEY (printer_pk)
        REFERENCES printers (id) ON DELETE CASCADE
);
CREATE INDEX ix_cartridge_fittings_serial ON cartridge_fittings (serial);
CREATE INDEX ix_cartridge_fittings_open ON cartridge_fittings (printer_pk, pen, removed_at);
