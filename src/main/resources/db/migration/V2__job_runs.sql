-- The table that records what was printed and when.

CREATE TABLE job_runs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    printer_pk INTEGER NOT NULL,
    label VARCHAR(24) NOT NULL,
    label_revision INTEGER DEFAULT 0 NOT NULL,
    outcome VARCHAR(16) DEFAULT '' NOT NULL,
    target INTEGER DEFAULT 0 NOT NULL,
    printed INTEGER DEFAULT 0 NOT NULL,
    started_counter INTEGER DEFAULT 0 NOT NULL,
    started_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP(6) WITH TIME ZONE,
    elapsed_s DOUBLE PRECISION DEFAULT 0 NOT NULL,
    operator VARCHAR(32) DEFAULT '' NOT NULL,
    detail VARCHAR(255) DEFAULT '' NOT NULL,
    CONSTRAINT pk_job_runs PRIMARY KEY (id),
    CONSTRAINT fk_job_runs_printer_pk_printers FOREIGN KEY (printer_pk)
        REFERENCES printers (id) ON DELETE CASCADE
);
CREATE INDEX ix_job_runs_label ON job_runs (label);
CREATE INDEX ix_job_runs_printer_started ON job_runs (printer_pk, started_at);
