-- Every table the first release needs.

CREATE TABLE printers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    printer_id VARCHAR(32) NOT NULL,
    endpoint VARCHAR(128) NOT NULL,
    kind VARCHAR(16) DEFAULT 'tcp' NOT NULL,
    line VARCHAR(32) DEFAULT '' NOT NULL,
    description VARCHAR(255) DEFAULT '' NOT NULL,
    family VARCHAR(16) DEFAULT '' NOT NULL,
    firmware VARCHAR(32) DEFAULT '' NOT NULL,
    enabled BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    seen_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_printers PRIMARY KEY (id)
);
CREATE UNIQUE INDEX ix_printers_printer_id ON printers (printer_id);

CREATE TABLE poll_samples (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    printer_pk INTEGER NOT NULL,
    at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reachable BOOLEAN DEFAULT TRUE NOT NULL,
    state VARCHAR(16) DEFAULT '' NOT NULL,
    alarms INTEGER DEFAULT 0 NOT NULL,
    printed INTEGER DEFAULT 0 NOT NULL,
    head_temperature_c DOUBLE PRECISION,
    line_speed_mm_per_min DOUBLE PRECISION,
    duration_s DOUBLE PRECISION DEFAULT 0 NOT NULL,
    error VARCHAR(255) DEFAULT '' NOT NULL,
    CONSTRAINT pk_poll_samples PRIMARY KEY (id),
    CONSTRAINT fk_poll_samples_printer_pk_printers FOREIGN KEY (printer_pk)
        REFERENCES printers (id) ON DELETE CASCADE
);
CREATE INDEX ix_poll_samples_at ON poll_samples (at);
CREATE INDEX ix_poll_samples_printer_at ON poll_samples (printer_pk, at);

CREATE TABLE alarm_records (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    printer_pk INTEGER NOT NULL,
    name VARCHAR(32) NOT NULL,
    severity VARCHAR(16) DEFAULT 'warning' NOT NULL,
    raised_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    cleared_at TIMESTAMP(6) WITH TIME ZONE,
    seen INTEGER DEFAULT 1 NOT NULL,
    acknowledged_by VARCHAR(32) DEFAULT '' NOT NULL,
    CONSTRAINT pk_alarm_records PRIMARY KEY (id),
    CONSTRAINT fk_alarm_records_printer_pk_printers FOREIGN KEY (printer_pk)
        REFERENCES printers (id) ON DELETE CASCADE
);
CREATE INDEX ix_alarm_records_name ON alarm_records (name);
CREATE INDEX ix_alarm_records_open ON alarm_records (printer_pk, cleared_at);

CREATE TABLE label_revisions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(24) NOT NULL,
    revision INTEGER DEFAULT 1 NOT NULL,
    digest VARCHAR(32) NOT NULL,
    source VARCHAR(8192) NOT NULL,
    height_dots INTEGER DEFAULT 0 NOT NULL,
    interactive BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_by VARCHAR(32) DEFAULT '' NOT NULL,
    CONSTRAINT pk_label_revisions PRIMARY KEY (id),
    CONSTRAINT uq_label_revision UNIQUE (name, revision)
);
CREATE INDEX ix_label_revisions_name ON label_revisions (name);

CREATE TABLE config_snapshots (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    printer_pk INTEGER NOT NULL,
    taken_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    digest VARCHAR(32) NOT NULL,
    payload VARCHAR(8192) NOT NULL,
    reason VARCHAR(64) DEFAULT '' NOT NULL,
    taken_by VARCHAR(32) DEFAULT '' NOT NULL,
    CONSTRAINT pk_config_snapshots PRIMARY KEY (id),
    CONSTRAINT fk_config_snapshots_printer_pk_printers FOREIGN KEY (printer_pk)
        REFERENCES printers (id) ON DELETE CASCADE
);
CREATE INDEX ix_config_snapshots_digest ON config_snapshots (digest);
CREATE INDEX ix_config_snapshots_printer_at ON config_snapshots (printer_pk, taken_at);
