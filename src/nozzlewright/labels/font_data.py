def _glyphs() -> dict[str, Glyph]:
    """Compile every authored pattern once."""
    compiled: dict[str, Glyph] = {}
    for char, pattern in PATTERNS.items():
        compiled[char] = compile_glyph(char, tuple(pattern.split(_ROW_SEPARATOR)))
    return compiled


def build_five_by_seven() -> BitmapFont:
    """The stock font, freshly compiled."""
    return BitmapFont(name="5x7", height=7, glyphs=_glyphs(), spacing=1, fallback="?")


