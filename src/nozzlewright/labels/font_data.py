"""The built in font.

Five wide by seven high, the smallest thing that still reads on a carton after
a week in a chiller. This is the font the machine boots with and the one every
site falls back to when a custom font fails to load.

Patterns are authored as rows separated by a slash, top row first. A hash fires
a nozzle and a dot does not. The character set is what coding actually uses:
digits, capitals, and the punctuation that appears in a lot code, a date, a best
before or a shift marker. Lower case is deliberately absent. It does not survive
seven nozzles and no customer has ever asked for it.
"""

